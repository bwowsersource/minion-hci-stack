#!/usr/bin/env bash
# Prepares an Orange Pi 5 Pro (RK3588, Mali-G610) for GPU inference without root:
# installs a newer Mesa `panvk` Vulkan driver into a private folder instead of the
# system. Debian trixie ships Mesa 25.0.7, whose panvk fails on this stack with
# vk::CommandBuffer::end: ErrorOutOfDeviceMemory; trixie-backports has a much newer one.
#
# It downloads the backports packages (no root needed), unpacks them into
# $MESA26_DIR (default ~/mesa26), points the Vulkan driver manifest at the unpacked
# library, and writes $MESA26_DIR/env.sh. Nothing outside $MESA26_DIR is touched.
#
# Use it afterwards with:
#   source ~/mesa26/env.sh && bun run demo <modelsPath> "<text>"
# Undo it by not sourcing env.sh, or with `rm -rf ~/mesa26`.
#
# Usage: prepare-orangepi5pro.sh [-f|--force]
#   -f, --force   download and unpack again even if $MESA26_DIR is already prepared
# Environment:
#   MESA26_DIR    install folder (default ~/mesa26)
#   MESA26_EXTRA  extra packages to fetch and unpack too, space separated; `name` is taken from
#                 trixie, `name/trixie-backports` from backports
set -euo pipefail

log() { echo "[prepare] $*"; }
die() {
    echo "[prepare] $*" >&2
    exit 1
}

FORCE=0
for arg in "$@"; do
    case "$arg" in
        -f | --force) FORCE=1 ;;
        *) die "unknown argument: ${arg} (usage: prepare-orangepi5pro.sh [-f|--force])" ;;
    esac
done

DEST="${MESA26_DIR:-$HOME/mesa26}"
LIBDIR="$DEST/root/usr/lib/aarch64-linux-gnu"
ICD="$DEST/root/usr/share/vulkan/icd.d/panfrost_icd.json"
RELEASE="trixie-backports"

[ "$(uname -m)" = "aarch64" ] || die "this prepares an aarch64 board (found $(uname -m))"
for tool in apt-get dpkg-deb sed; do
    command -v "$tool" >/dev/null 2>&1 || die "${tool} not found"
done
grep -rqs "$RELEASE" /etc/apt/sources.list /etc/apt/sources.list.d/ ||
die "no ${RELEASE} apt source found; add 'deb http://deb.debian.org/debian ${RELEASE} main' (needs root) and run apt update"

# Downloads packages (`name` for the stable release, `name/release` for another) into
# debs/ and unpacks everything there into root/.
fetch() {
    (cd "$DEST/debs" && apt-get download "$@")
    for deb in "$DEST"/debs/*.deb; do
        dpkg-deb -x "$deb" "$DEST/root"
    done
}

# Package that provides a library the backports driver links against but trixie may not install.
package_for() {
    case "$1" in
        libdisplay-info.so.2) echo libdisplay-info2 ;;
    esac
}

missing_libs() { LD_LIBRARY_PATH="$LIBDIR" ldd "$LIBDIR/libvulkan_panfrost.so" | awk '/not found/ {print $1}'; }

if [ "$FORCE" = "1" ] || [ ! -f "$ICD" ]; then
    log "downloading mesa-vulkan-drivers from ${RELEASE} into ${DEST}/debs"
    rm -rf "$DEST/debs" "$DEST/root"
    mkdir -p "$DEST/debs" "$DEST/root"
    # shellcheck disable=SC2086
    fetch "mesa-vulkan-drivers/${RELEASE}" ${MESA26_EXTRA:-}
else
    log "${DEST} is already prepared (use --force to download again)"
fi

[ -f "$ICD" ] || die "${ICD} not found after unpacking; the package layout may have changed"
[ -f "$LIBDIR/libvulkan_panfrost.so" ] || die "${LIBDIR}/libvulkan_panfrost.so not found after unpacking"

# the driver may link libraries this system doesn't have; fetch the ones we know the package of
extras=()
unknown=()
for lib in $(missing_libs); do
    pkg="$(package_for "$lib")"
    if [ -n "$pkg" ]; then extras+=("$pkg"); else unknown+=("$lib"); fi
done
if [ "${#extras[@]}" -gt 0 ]; then
    log "fetching missing libraries: ${extras[*]}"
    fetch "${extras[@]}"
    unknown=()
    for lib in $(missing_libs); do unknown+=("$lib"); done
fi
[ "${#unknown[@]}" -eq 0 ] ||
die "the driver needs libraries this system lacks: ${unknown[*]}. Find their packages and re-run with MESA26_EXTRA=\"<package[/release]> ...\" --force"

# the manifest names the library relatively; make it absolute so the loader finds ours
sed -i "s|\"library_path\": *\"[^\"]*\"|\"library_path\": \"${LIBDIR}/libvulkan_panfrost.so\"|" "$ICD"

cat >"$DEST/env.sh" <<EOT
# Generated by scripts/prepare-orangepi5pro.sh: use the private Mesa panvk driver.
export VK_DRIVER_FILES="${ICD}"
export LD_LIBRARY_PATH="${LIBDIR}\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
EOT

log "prepared ${DEST} ($(basename "$(ls "$DEST"/debs/mesa-vulkan-drivers_*.deb)"))"
if command -v vulkaninfo >/dev/null 2>&1; then
    log "Vulkan devices with the private driver:"
    (
        # shellcheck disable=SC1091
        . "$DEST/env.sh"
        vulkaninfo --summary 2>/dev/null | grep -E "deviceName|driverName|driverInfo" | sed 's/^[[:space:]]*/[prepare]   /'
    ) || true
fi
log "to use it: source ${DEST}/env.sh"
log " source ~/mesa26/env.sh && bun run demo ...."